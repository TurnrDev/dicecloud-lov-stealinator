/*
 * Emit a Mongo shell program for a collision-safe local DiceCloud restore.
 * It preserves all library/node IDs and legacy tree references. The program
 * refuses to overwrite an existing library and only changes the local user
 * selected by username.
 *
 * Usage: node tools/emit-local-restore.js <export.json> <local-username>
 */
const fs = require('node:fs/promises');

const [source, username, option] = process.argv.slice(2);
if (!source || !username) throw new Error('Usage: node tools/emit-local-restore.js <export.json> <local-username>');
const replace = option === '--replace';

async function main() {
  const snapshot = JSON.parse(await fs.readFile(source, 'utf8'));
  if (!snapshot.library || !Array.isArray(snapshot.libraryNodes)) throw new Error('Not a DiceCloud library export.');

  const ids = new Set(snapshot.libraryNodes.map(node => node._id));
  const dangling = [];
  for (const node of snapshot.libraryNodes) {
    const refs = [node.parent, ...(node.ancestors || [])].filter(ref => ref?.collection === 'libraryNodes');
    for (const ref of refs) if (!ids.has(ref.id)) dangling.push({ node: node._id, missing: ref.id });
  }
  if (dangling.length) throw new Error(`Refusing restore: ${dangling.length} dangling tree references.`);

  // Site-specific collaboration data must not be restored into the local DB.
  const library = { ...snapshot.library, writers: [], readers: [] };
  delete library.subscriberCount;
  delete library.showInMarket;
  const libraryNodes = modernizeTree(snapshot.libraryNodes, library._id);
  const payload = JSON.stringify({ username, library, libraryNodes, replace });
  process.stdout.write(`// Generated by emit-local-restore.js; local database only.\n`);
  process.stdout.write(`const payload = ${payload};\n`);
  process.stdout.write(`const user = db.users.findOne({ username: payload.username });\n`);
  process.stdout.write(`if (!user) throw new Error('Local user not found: ' + payload.username);\n`);
  process.stdout.write(`if (!payload.replace && db.libraries.findOne(payload.library._id)) throw new Error('Library ID already exists: ' + payload.library._id);\n`);
  process.stdout.write(`if (!payload.replace && db.libraryNodes.countDocuments({ _id: { $in: payload.libraryNodes.map(n => n._id) } })) throw new Error('One or more node IDs already exist');\n`);
  process.stdout.write(`if (payload.replace) { db.libraryNodes.deleteMany({ $or: [{ 'root.id': payload.library._id }, { 'ancestors.id': payload.library._id }, { 'parent.id': payload.library._id }] }); db.libraries.deleteOne({ _id: payload.library._id }); }\n`);
  process.stdout.write(`payload.library.owner = user._id;\n`);
  process.stdout.write(`db.libraries.insertOne(payload.library);\n`);
  process.stdout.write(`db.libraryNodes.insertMany(payload.libraryNodes, { ordered: true });\n`);
  process.stdout.write(`db.users.updateOne({ _id: user._id }, { $addToSet: { subscribedLibraries: payload.library._id } });\n`);
  process.stdout.write(`print('Restored ' + payload.library.name + ': ' + payload.libraryNodes.length + ' nodes');\n`);
}

function modernizeTree(rawNodes, libraryId) {
  const nodes = rawNodes.map(raw => {
    const node = { ...raw, root: { collection: 'libraries', id: libraryId } };
    if (raw.parent?.collection === 'libraryNodes') node.parentId = raw.parent.id;
    else delete node.parentId;
    return node;
  });
  const children = new Map();
  for (const node of nodes) {
    const key = node.parentId || '__root__';
    const siblings = children.get(key) || [];
    siblings.push(node);
    children.set(key, siblings);
  }
  for (const siblings of children.values()) siblings.sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  let counter = 0;
  const visit = node => {
    node.left = ++counter;
    for (const child of children.get(node._id) || []) visit(child);
    node.right = ++counter;
  };
  for (const root of children.get('__root__') || []) visit(root);
  if (counter !== nodes.length * 2) throw new Error('Tree is disconnected or cyclic.');
  return nodes;
}

main().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
